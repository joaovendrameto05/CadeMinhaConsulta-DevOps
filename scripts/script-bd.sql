-- 1. Tabela de Unidades de Saúde (UBS / AME)
CREATE TABLE TB_CMC_UNIDADE (
    ID_UNIDADE NUMBER(10) PRIMARY KEY,
    NM_UNIDADE VARCHAR2(120) NOT NULL,
    CD_CNES    VARCHAR2(20)  NOT NULL,
    NM_CIDADE  VARCHAR2(80)  NOT NULL,
    SG_UF      CHAR(2)       NOT NULL,
    DT_CRIACAO DATE DEFAULT SYSDATE NOT NULL
);

-- 2. Tabela de Especialidades e Procedimentos SUS (Relacionada à Unidade)
CREATE TABLE TB_CMC_ESPECIALIDADE (
    ID_ESPECIALIDADE NUMBER(10) PRIMARY KEY,
    NM_ESPECIALIDADE VARCHAR2(100) NOT NULL,
    CD_SIGTAP        VARCHAR2(20)  NOT NULL,
    VL_SIGTAP        NUMBER(10,2)  NOT NULL,
    ID_UNIDADE       NUMBER(10)    NOT NULL,
    DT_CRIACAO       DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_CMC_ESP_UNIDADE FOREIGN KEY (ID_UNIDADE)
        REFERENCES TB_CMC_UNIDADE (ID_UNIDADE)
);

-- 3. Tabela de Consultas Agendadas (Monitoramento de Absenteísmo e Notificações)
CREATE TABLE TB_GS_CONSULTA (
    ID_CONSULTA        NUMBER(38,0) PRIMARY KEY,
    ID_USUARIO         NUMBER(38,0) NOT NULL,
    STATUS_CONSULTA    VARCHAR2(10 CHAR) NOT NULL,
    DATA_HORA_CONSULTA DATE NOT NULL
);

